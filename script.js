const supported = ['en','fr','ja'];

function resolveLanguage(){
  const params = new URLSearchParams(location.search);
  const urlLang = params.get('lang');
  const stored = localStorage.getItem('bath-doc-lang');
  const browser = (navigator.languages?.[0] || navigator.language || 'en').toLowerCase();
  const browserLang = browser.startsWith('fr') ? 'fr' : browser.startsWith('ja') ? 'ja' : 'en';
  return supported.includes(urlLang) ? urlLang : supported.includes(stored) ? stored : browserLang;
}

function applyLanguage(lang, persist=false){
  if(!supported.includes(lang)) lang='en';
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.dataset.i18n;
    if(translations[lang][key]) el.textContent = translations[lang][key];
  });
  document.querySelectorAll('[data-lang]').forEach(btn=>{
    btn.setAttribute('aria-pressed', String(btn.dataset.lang === lang));
  });
  const menuToggle = document.querySelector('.menu-toggle');
  if (menuToggle) {
    const isOpen = menuToggle.getAttribute('aria-expanded') === 'true';
    menuToggle.setAttribute('aria-label', translations[lang][isOpen ? 'menuClose' : 'menuOpen']);
  }
  // Update non-visible navigation and contact labels when switching to Japanese.
  // Other language labels keep their existing values.
  const ariaLabels = lang === 'ja'
    ? {brand: 'Japan Through Bathing Culture、ページの先頭へ', nav: 'メインナビゲーション', language: '言語の切り替え', contact: '連絡方法'}
    : {brand: 'Japan Through Bathing Culture, home', nav: 'Primary navigation', language: 'Language', contact: 'Contact options'};
  [['.brand', ariaLabels.brand], ['.main-nav', ariaLabels.nav], ['.language-switcher', ariaLabels.language], ['.contact-actions', ariaLabels.contact]].forEach(([selector, label]) => {
    document.querySelector(selector)?.setAttribute('aria-label', label);
  });
  if(persist) localStorage.setItem('bath-doc-lang', lang);
  const title = translations[lang].heroTitle;
  document.title = `${title}: ${translations[lang].footerText}`;
  const description = translations[lang].heroStatement;
  document.querySelector('meta[name="description"]')?.setAttribute('content', description);
  document.querySelector('meta[property="og:title"]')?.setAttribute('content', title);
  document.querySelector('meta[property="og:description"]')?.setAttribute('content', description);
}

document.querySelectorAll('[data-lang]').forEach(btn=>{
  btn.addEventListener('click', ()=>{
    const lang = btn.dataset.lang;
    applyLanguage(lang, true);
    const url = new URL(location.href);
    url.searchParams.set('lang', lang);
    history.replaceState({}, '', url);
  });
});

applyLanguage(resolveLanguage());


const menuToggle = document.querySelector('.menu-toggle');

const decodeContact = values => String.fromCharCode(...values);

const contactTargets = {
  email: () => {
    const local = decodeContact([97,114,110,97,117,100,109,97,114,113,117,101,122]);
    const domain = decodeContact([103,109,97,105,108,46,99,111,109]);
    return 'mailto:' + local + '@' + domain;
  },
  whatsapp: () => {
    const number = decodeContact([51,51,54,55,51,49,56,51,54,56,54]);
    return 'https://wa.me/' + number;
  }
};

document.querySelectorAll('[data-contact]').forEach(button => {
  button.addEventListener('click', () => {
    const type = button.dataset.contact;
    const target = contactTargets[type]?.();
    if (!target) return;

    if (type === 'whatsapp') {
      window.open(target, '_blank', 'noopener,noreferrer');
    } else {
      window.location.href = target;
    }
  });
});


const navLinks = [...document.querySelectorAll('.main-nav a[href^="#"]')];
const navSections = navLinks
  .map(link => {
    const id = link.getAttribute('href')?.slice(1);
    const section = id ? document.getElementById(id) : null;
    return section ? { link, section } : null;
  })
  .filter(Boolean);

if (navSections.length) {
  let navTicking = false;

  const updateActiveNav = () => {
    const headerHeight = document.querySelector('.site-header')?.offsetHeight || 0;
    const marker = window.scrollY + headerHeight + 24;
    let active = null;

    for (const item of navSections) {
      if (item.section.offsetTop <= marker) active = item;
      else break;
    }

    navLinks.forEach(link => {
      const isActive = active?.link === link;
      if (isActive) link.setAttribute('aria-current', 'location');
      else link.removeAttribute('aria-current');
    });

    const activeHash = active?.link.getAttribute('href');
    if (activeHash && location.hash !== activeHash) {
      const url = new URL(location.href);
      url.hash = activeHash;
      history.replaceState(history.state, '', url);
    } else if (!active && navLinks.some(link => link.getAttribute('href') === location.hash)) {
      const url = new URL(location.href);
      url.hash = '';
      history.replaceState(history.state, '', url);
    }

    navTicking = false;
  };

  const requestNavUpdate = () => {
    if (navTicking) return;
    navTicking = true;
    requestAnimationFrame(updateActiveNav);
  };

  updateActiveNav();
  window.addEventListener('scroll', requestNavUpdate, { passive: true });
  window.addEventListener('resize', requestNavUpdate);
}
